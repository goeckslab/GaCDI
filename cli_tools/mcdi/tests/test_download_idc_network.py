from __future__ import annotations

from pathlib import Path

import pytest

from mcdi.download import engine
from mcdi.download.sources import detect_source
from mcdi.download.sources.idc import IDCSource

# A small (3 objects, ~105KB total), stable IDC series - itself one of
# idc-index's own maintained test fixtures - used purely to exercise the
# download pipeline against the real idc-index metadata index and the real
# public idc-open-data S3 bucket.
CRDC_SERIES_UUID = "28621ba9-1aca-4aab-a2a1-f6d2c3e2ab19"
SERIES_INSTANCE_UID = "1.3.6.1.4.1.14519.5.2.1.7695.1700.153974929648969296590126728101"
EXPECTED_FILE_COUNT = 3
EXPECTED_TOTAL_SIZE = 104904


def _write_s5cmd_manifest(path: Path) -> None:
    path.write_text(
        "# generated by the IDC portal\n"
        f"cp s3://idc-open-data/{CRDC_SERIES_UUID}/* .\n"
    )


def _write_csv_manifest(path: Path) -> None:
    path.write_text(
        "PatientID,collection_id,StudyInstanceUID,SeriesInstanceUID,source_DOI,study_uuid,series_uuid,gcs_url\n"
        f"ISPY1_1181,ispy1,1.3.6.1.4.1.14519.5.2.1.7695.1700.251181729149149196962664129666,"
        f"{SERIES_INSTANCE_UID},,,,gs://placeholder\n"
    )


@pytest.mark.network
@pytest.mark.parametrize("write_manifest,expected_source", [
    (_write_s5cmd_manifest, "idc"),
    (_write_csv_manifest, "idc"),
])
def test_idc_manifest_round_trip(tmp_path, write_manifest, expected_source):
    manifest_path = tmp_path / "idc_manifest.txt"
    write_manifest(manifest_path)

    assert detect_source(manifest_path) == expected_source

    source = IDCSource()
    entries = source.parse_manifest(manifest_path)
    assert len(entries) == EXPECTED_FILE_COUNT
    assert sum(e.size for e in entries) == EXPECTED_TOTAL_SIZE

    output_dir = tmp_path / "downloads"
    failures = engine.check_access(entries, source, output_dir=output_dir, workers=4)
    assert failures == []

    results = engine.run(entries, source, output_dir, workers=4, verify=True)
    assert {r.status for r in results} == {"downloaded"}
    for entry in entries:
        dest = output_dir / entry.rel_dir / entry.filename
        assert dest.is_file()
        assert dest.stat().st_size == entry.size

    # Re-running against the same output dir should skip files already
    # downloaded rather than re-fetching them (no checksum to verify against
    # for IDC entries, but presence + size is still enough to skip).
    results_again = engine.run(entries, source, output_dir, workers=4, verify=True)
    assert {r.status for r in results_again} == {"skipped"}
