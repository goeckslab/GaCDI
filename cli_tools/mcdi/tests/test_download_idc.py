def test_known_open_vouches_for_every_entry(tmp_path, requests_mock):
    manifest = tmp_path / "m.s5cmd"
    manifest.write_text(f"cp s3://idc-open-data/{SERIES_A.crdc_series_uuid}/* .\n")
    _mock_listing(
        requests_mock,
        "idc-open-data",
        {SERIES_A.crdc_series_uuid: [([(f"{SERIES_A.crdc_series_uuid}/a.dcm", 10)], False)]},
    )
    source = IDCSource(lookup=FakeLookup({SERIES_A.crdc_series_uuid: SERIES_A}))
    entries = source.parse_manifest(manifest)

    assert source.known_open(entries, session=None) == {e.file_id for e in entries}


